package com.gentics.mesh.portal.api.content;

import io.vertx.core.json.JsonArray;
import io.vertx.core.json.JsonObject;
import io.vertx.ext.web.RoutingContext;
import org.apache.commons.lang.StringUtils;

/**
 * Transforms a GraphQL result loading the navigation data into a form usable by the portal.
 */
public interface NavigationTransformer {

	/**
	 * Transform the GraphQL query result to an array containing the navigation.
	 *
	 * @param queryResult The GraphQL query result with the navigation data
	 * @param rc The Routing-Context of the page request where the navigation is loaded into
	 * @return An <code>JsonArray</code> containing the processed navigation
	 */
	JsonArray transform(JsonObject queryResult, RoutingContext rc);

	/**
	 * Additional information that will be added to the cache key generated by
	 * the {@code NavigationHandler}.
	 *
	 * <p>
	 *     The default implementation will return an empty string, so the
	 *     default cache key will <em>not</em> be modified.
	 * </p>
	 *
	 * <p>
	 *     By default the navigation handler uses the following information
	 *     to create a cache key:
	 *     <ul>
	 *         <li>the portal language</li>
	 *         <li>the users roles, and</li>
	 *         <li>the branch used for the current request</li>
	 *     </ul>
	 * </p>
	 *
	 * @param rc The current routing context
	 * @return String that will be added to the {@code NavigationHandlers} cache key
	 */
	default String additionalCacheKey(RoutingContext rc) {
		return "";
	}
}
